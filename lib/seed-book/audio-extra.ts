/** Dars topshiriqlariga qo'shimcha audio topshiriqlarni o'z bo'limi oxiriga qo'shadi. */
export function withExtraAudio<T extends { code: string; exercises: BookExercise[] }>(lesson: T): T {
  const extra = [...(EXTRA_AUDIO[lesson.code] ?? []), ...(EXTRA_AUDIO[`${lesson.code}+`] ?? [])];
  if (extra.length === 0) return lesson;
  const exercises = [...lesson.exercises];
  for (const ex of extra) {
    let at = -1;
    exercises.forEach((e, i) => {
      if (e.section === ex.section) at = i;
    });
    exercises.splice(at >= 0 ? at + 1 : exercises.length, 0, ex);
  }
  return { ...lesson, exercises };
}
